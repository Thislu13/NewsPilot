"""簇分析提示词 — LLM 分析一组新闻事件，生成簇描述并剔除离群事件"""

CLUSTER_ANALYSIS_PROMPT = """你是一个新闻事件分析助手。任务：分析一组事件，生成簇描述并剔除不属于该组的事件。

输入：一组新闻事件，每条格式为 [编号] [发布时间] 事件描述。

请完成以下任务：
1. brief_description：核心话题的一句话提炼。要求：
   - 仅描述话题本质，禁止包含任何时间、日期、年份、月份信息
   - 错误示例："2026年2月至3月的中美贸易摩擦" → 正确示例："中美贸易摩擦"
   - 错误示例："近期日本核污水排放争议" → 正确示例："日本福岛核污水排放争议"
   - 用于后续向量匹配，请精确提炼话题关键词
2. detailed_description：话题概述，严格按以下格式输出：
   第一部分：发展梗概（不超过200字）
   在时间线之前，用一段客观文字概括该话题的发展脉络。只描述：何时爆发、经历了哪些关键转折、当前处于什么状态。不评价、不预测、不使用修饰性语言。末尾以括号标注时间边界，格式为"（截至YYYY年M月D日）"，日期取事件列表中最晚的发布时间。

   第二部分：事件时间线
   - 按时间顺序将事件划分为若干阶段，每个阶段用【起始日期-结束日期｜阶段标题】标记。阶段划分标准是事件密集度或事态性质变化。阶段标题不超过20个字，只描述事实不评价。
   - 只陈述事实：禁止使用任何评价性、判断性、预测性表述。以下词语禁止出现："深远影响"、"重大挑战"、"脆弱性"、"高度关注"、"显示出"、"标志着"、"意味着"、"反映出"、"不仅…还…"、"对…产生…影响"以及任何无法从事件文本中直接推导出的结论。
   - 保留可量化信息：数字、规模、具体目标、参与方等硬信息必须保留，优先级高于定性描述。
   - 去重与合并：同一日期、同一事件被多次报道且表述一致时，合并为一条。
   - 时间线的第一句用一句话说明该话题的时间起点和核心事件。
   - 每条事实控制在一句话以内。阶段内事件按日期从早到晚排列。

   两部分之间用 --- 分隔。
3. weekly_description：近七天发展总结。客观陈述近七天的事件进展，禁止评价性、预测性表述，禁止出现"深远影响"、"重大挑战"、"标志着"、"意味着"等词语。只描述发生了什么，不评价意义或影响。末尾以括号标注最新事件日期，格式为"（截至YYYY年M月D日）"，日期取近七天事件中最晚的发布时间。如果无近七天事件则必须写"暂无近期发展（截至YYYY年M月D日）"，不得输出空字符串、空白字符串或 null。
4. recent_description：当前最新动态的客观概述。只陈述最新事实，禁止评价和修饰，50字以内。末尾以括号标注最新事件日期，格式为"（截至YYYY年M月D日）"。如果信息不足以形成明确动态，也必须写"暂无最新动态（截至YYYY年M月D日）"，不得输出空字符串、空白字符串或 null。
5. outlier_events：不属于该组的事件编号列表（0-indexed，与输入顺序对应）

判断标准：
- 如果一个事件与该组核心话题明显无关，应剔除
- 宁可保守，只在明显不相关时剔除

输出要求：
- 必须输出且仅输出一个合法 JSON 对象，不要包含任何其他文字、注释或markdown标记
- JSON 中的字符串值如果包含双引号，必须用 \" 转义；换行用 \n 转义
- 不要在 JSON 值中使用未转义的特殊字符

输出格式：
{"brief_description":"...","detailed_description":"...","weekly_description":"...","recent_description":"...","outlier_events":[0,3,7]}"""
